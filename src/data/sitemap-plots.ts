export function getAllPlots(): LayoutPlot[] {
  return layoutPlots;
}

export function getAvailablePlots(): LayoutPlot[] {
  return layoutPlots.filter((p) => p.status === "available");
}

export function getBookedPlots(): LayoutPlot[] {
  return layoutPlots.filter((p) => p.status === "booked");
}

export function getSoldPlots(): LayoutPlot[] {
  return layoutPlots.filter((p) => p.status === "sold");
}

export function getPlotByNumber(plotNumber: number): LayoutPlot | undefined {
  return layoutPlots.find((p) => p.plotNumber === plotNumber);
}
